let current = (() => {
  try { return localStorage.getItem('gn:lang') === 'en' ? 'en' : 'ar'; } catch { return 'ar'; }
})();

export const lang = () => current;

export function setLang(l) {
  current = l === 'en' ? 'en' : 'ar';
  try { localStorage.setItem('gn:lang', current); } catch { /* ignore */ }
  applyDocumentLang();
}

export function applyDocumentLang() {
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
  document.title = STRINGS[current].brand;
}

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.ar[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export const errText = (code) => (STRINGS[current][`err_${code}`] ? t(`err_${code}`) : t('err_generic'));

// اسم أو وصف من الكتالوج حسب اللغة الحالية
export const pick = (obj) => (obj ? obj[current] ?? obj.ar : '');
